package com.gojeom.ai.prompt;

import java.util.List;

/**
 * 비교 이미지 생성 프롬프트. (PRD §8.1 [5] · API.md §7.6 · ARCHITECTURE.md §6.5)
 *
 * <p><b>이 단계가 만드는 것은 "합성"이다.</b> 사용자 본인 사진을 기준으로 두고,
 * 참고 사진(추구미)에서 <b>피부와 헤어스타일</b>을 가져와 입힌다. 결과는
 * "내가 저 머리와 저 피부였다면" 이다.
 *
 * <p><b>G-2와의 경계</b> — "타인의 얼굴을 복제하지 않는다"는 <b>이목구비와 골격</b>,
 * 즉 그 사람이 누구인지를 결정하는 부분을 말한다. 헤어스타일과 피부 상태는 정체성이
 * 아니라 바꿀 수 있는 요소이고, 애초에 사용자가 그걸 참고하려고 사진을 올린 것이다.
 * 그래서 아래처럼 가른다.
 *
 * <table>
 *   <caption>합성 경계</caption>
 *   <tr><th>참고 사진에서 가져오는 것</th><th>사용자 사진에서 지키는 것</th></tr>
 *   <tr><td>헤어스타일 (길이·형태·앞머리·컬·색)</td><td>이목구비의 형태와 배치</td></tr>
 *   <tr><td>피부 <b>상태</b> (결·매끄러움·톤의 균일함·생기)</td><td>얼굴 골격과 윤곽</td></tr>
 *   <tr><td>전체 분위기와 색감</td><td>나이 · 인종 · 성별 · 체형 · <b>고유 피부색</b></td></tr>
 * </table>
 *
 * <p><b>피부는 "상태"만 가져오고 "피부색"은 바꾸지 않는다.</b> 두 가지 이유다.
 * <ul>
 *   <li>피부색은 인종과 얽혀 있다. 밝게·어둡게 바꾸는 기능은 미용 AI가 넘지 말아야 할
 *       선이고, "나이·인종·성별을 바꾸지 않는다"는 규칙과도 정면으로 충돌한다.</li>
 *   <li>이 제품이 말하는 피부는 <b>상태</b>다. 우선순위의 SKIN도, 결과지의 피부 제안도
 *       수분·결·톤의 균일함을 다루지 피부색을 다루지 않는다. (PRD F-02 · §8.1)</li>
 * </ul>
 * 실제로 톤 자체를 옮기라고 했더니 모델이 "인종 유지" 규칙과 충돌해 아무것도
 * 하지 않았다. 요구를 상태로 좁히자 의도대로 동작한다.
 *
 * <p>이미지 모델은 JSON 스키마를 쓰지 않아 텍스트 프롬프트가 유일한 통제 수단이다.
 * 그래서 문구를 길고 명시적으로 쓴다.
 */
public final class ImageGenerationPrompt {

    private ImageGenerationPrompt() {
    }

    /**
     * @param keywordLabels  사용자가 확정한 고점 키워드
     * @param referenceCount 참고 사진 장수. 0이면 이 단계 자체가 실행되지 않는다
     */
    public static String build(List<String> keywordLabels, int referenceCount) {
        String keywords = keywordLabels.isEmpty() ? "자연스럽고 정돈된 인상" : String.join(", ", keywordLabels);

        return """
                첫 번째 이미지는 **사용자 본인의 사진**이다. 이 사진이 결과물의 기준이자 중심이다.
                %s

                지향하는 인상: %s

                [사용자 사진에서 반드시 그대로 유지할 것]
                - **얼굴 생김새와 정체성.** 결과물은 첫 번째 사진과 같은 사람으로 보여야 한다.
                - 눈·코·입의 형태와 배치, 얼굴 윤곽과 골격, 이목구비 비율.
                - 나이, 인종, 성별, 체형.
                - 다른 사람의 얼굴을 붙이거나 참고 인물을 닮게 만들지 않는다.
                - 성형한 얼굴을 만들지 않는다. 마르게 하거나 체형을 과장하지 않는다.

                [결과물의 조건]
                - 사진처럼 보이는 자연스러운 결과물. 과한 보정이나 인공적인 광택을 넣지 않는다.
                - 합성 티가 나는 경계선이나 이질감이 없어야 한다.
                - 조명과 각도는 첫 번째 사진을 따른다.
                """.formatted(compositionRule(referenceCount), keywords);
    }

    /**
     * 참고 사진이 있을 때의 합성 규칙.
     *
     * <p>참고 사진이 없으면 합성할 대상이 없다. 그때는 키워드만 보고 정돈하는데,
     * 실제로는 호출부가 참고 사진이 없으면 이 단계를 아예 실행하지 않는다.
     */
    private static String compositionRule(int referenceCount) {
        if (referenceCount <= 0) {
            return "참고 사진 없이, 아래 인상에 맞게 자연스럽게 정돈된 모습으로 표현하라.";
        }
        return """
                두 번째 이미지부터는 사용자가 **닮고 싶어서 직접 올린 참고 사진**이다.

                [참고 사진에서 가져와 사용자에게 입힐 것]
                - **헤어스타일** — 길이, 형태, 앞머리 유무, 컬, 볼륨, 머리색까지 그대로 옮긴다.
                  이것이 이 합성에서 가장 눈에 띄어야 하는 변화다.
                - **피부 상태** — 결의 매끄러움, 톤의 균일함, 생기. 참고 사진의 피부가
                  더 정돈되어 보인다면 그 상태를 사용자 얼굴에 적용한다.
                - 전체적인 분위기와 색감, 조명의 느낌.

                [참고 사진에서 가져오면 안 되는 것]
                - **얼굴 생김새.** 눈·코·입의 모양, 얼굴형, 골격은 절대 가져오지 않는다.
                  참고 인물의 얼굴을 합성하거나 그 사람처럼 보이게 만들면 실패다.
                - **피부색 자체.** 사용자의 고유한 피부색은 그대로 둔다.
                  밝게 하거나 어둡게 하지 않는다. 바꾸는 것은 색이 아니라 상태다.
                - 체형, 나이, 인종, 성별.

                요약하면: **사용자의 얼굴에 참고 사진의 머리를 입히고, 피부는 상태만 정돈한다.**""";
    }
}
